"""Three Knots: why a spine IK curve needs three knots (MOTION_EDIT_RIG.md section 15).

Planar picture. A C1 piecewise-cubic Hermite curve, joints placed by arc length.
Render: uv run manim -qh --disable_caching three_knots.py ThreeKnots
"""
from moted_style import *
import numpy as np
from scipy.optimize import minimize

SX, SY, SC = -3.4, -2.5, 1.2          # local pose coords -> screen
TS = (0.0, 0.4, 1.0)           # knot parameters (mid takes its own arc fraction)
NJ = 6                         # joints in the chain


def scr(p):
    return np.array([p[0] * SC + SX, p[1] * SC + SY, 0.0])


def herm(p0, p1, m0, m1, dt, s):
    s = np.asarray(s)[:, None]
    h00 = 2 * s**3 - 3 * s**2 + 1
    h10 = s**3 - 2 * s**2 + s
    h01 = -2 * s**3 + 3 * s**2
    h11 = s**3 - s**2
    return h00 * p0 + h10 * dt * m0 + h01 * p1 + h11 * dt * m1


def curve3(P0, T0, M, T1, C, T2, n=240):
    """Three-knot curve (dP/dt tangents). Returns dense points."""
    a = herm(P0, M, T0, T1, TS[1], np.linspace(0, 1, n))
    b = herm(M, C, T1, T2, TS[2] - TS[1], np.linspace(0, 1, n))
    return np.vstack([a, b[1:]])


def place(pts, nj=NJ):
    """Joints at equal arc-length fractions along the dense curve."""
    seg = np.linalg.norm(np.diff(pts, axis=0), axis=1)
    cum = np.concatenate([[0], np.cumsum(seg)])
    want = np.linspace(0, cum[-1], nj)
    return np.stack([np.interp(want, cum, pts[:, 0]), np.interp(want, cum, pts[:, 1])], 1)


# --- the pose: generated by a three-knot curve, so it is reachable by construction
P0 = np.array([0.0, 0.0]); C = np.array([0.3, 4.2])
M_T = np.array([-1.0, 1.75])
T0_T = np.array([-1.3, 3.2]); T1_T = np.array([0.1, 4.6]); T2_T = np.array([2.2, 3.0])
true_pts = curve3(P0, T0_T, M_T, T1_T, C, T2_T)
TARGET = place(true_pts)


def two_knot_state(T0, T2):
    """A single cubic P0..C, re-expressed as a three-knot state at t=0.4 (exact)."""
    s = 0.4
    M = herm(P0, C, T0, T2, 1.0, [s])[0]
    ds = 1e-5
    d = (herm(P0, C, T0, T2, 1.0, [s + ds])[0] - herm(P0, C, T0, T2, 1.0, [s - ds])[0]) / (2 * ds)
    return M, T0, d, T2


def miss2(x):
    M, T0, T1, T2 = two_knot_state(x[:2], x[2:])
    return np.sum((place(curve3(P0, T0, M, T1, C, T2)) - TARGET) ** 2)


def best_two_knot():
    best = None
    rng = np.random.default_rng(3)
    for _ in range(12):
        r = minimize(miss2, rng.uniform(-3, 3, 4), method="Nelder-Mead",
                     options=dict(xatol=1e-7, fatol=1e-12, maxiter=4000))
        if best is None or r.fun < best.fun:
            best = r
    return best.x


BEST2 = best_two_knot()
TRUE_STATE = (M_T, T0_T, T1_T, T2_T)


class ThreeKnots(Scene):
    # ---------- geometry helpers ----------
    def state(self):
        s2 = two_knot_state(np.array([self.t0x.get_value(), self.t0y.get_value()]),
                            np.array([self.t2x.get_value(), self.t2y.get_value()]))
        b = self.blend.get_value()
        return tuple((1 - b) * np.asarray(a) + b * np.asarray(t) for a, t in zip(s2, TRUE_STATE))

    def dense(self):
        M, T0, T1, T2 = self.state()
        return curve3(P0, T0, M, T1, C, T2)

    def make_curve(self, color=YELLOW, width=5):
        def f():
            m = VMobject(stroke_color=color, stroke_width=width)
            m.set_points_as_corners([scr(p) for p in self.dense()[::3]])
            return m
        return always_redraw(f)

    def make_fit(self):
        def f():
            g = VGroup()
            j = place(self.dense())
            for k in range(NJ):
                g.add(Dot(scr(j[k]), radius=0.08, color=YELLOW))
            return g
        return always_redraw(f)

    def make_miss(self):
        def f():
            g = VGroup()
            j = place(self.dense())
            for k in range(NJ):
                d = np.linalg.norm(j[k] - TARGET[k])
                if d > 0.015:
                    g.add(Line(scr(TARGET[k]), scr(j[k]), color=RED, stroke_width=4))
            return g
        return always_redraw(f)

    def knots(self):
        def f():
            M = self.state()[0]
            g = VGroup(Dot(scr(P0), radius=0.14, color=ORANGE), Dot(scr(C), radius=0.14, color=ORANGE))
            if self.show_mid:
                g.add(Dot(scr(M), radius=0.14, color=ORANGE))
            return g
        return always_redraw(f)

    def side(self, tex_list, x=2.6, y0=2.3, gap=0.95, **kw):
        g = VGroup(*tex_list).arrange(DOWN, aligned_edge=LEFT, buff=0.38)
        g.move_to([x, y0 - g.height / 2, 0], aligned_edge=UP + LEFT) if False else None
        return g

    def tag(self, text, prev=None):
        t = Text(text, font_size=26, color=DIM).to_corner(UL, buff=0.45)
        if prev is None:
            self.play(FadeIn(t), run_time=0.5)
        else:
            self.play(ReplacementTransform(prev, t), run_time=0.5)
        return t

    # ---------- the film ----------
