        self.t0x, self.t0y, self.t2x, self.t2y = [ValueTracker(0) for _ in range(4)]
        self.blend = ValueTracker(0)
        self.t0x.set_value(0.0); self.t0y.set_value(1.5)
        self.t2x.set_value(0.0); self.t2y.set_value(1.5)

        title_card(self, "Three Knots", "Count what a representation can reach")

        # ===== Beat 1: a chain, and a curve it wants =====
        tg = self.tag("1   A spine at rest")
        bones = VGroup(*[Line(scr(TARGET[i]), scr(TARGET[i + 1]), color=BLUE, stroke_width=6)
                         for i in range(NJ - 1)])
        joints = VGroup(*[Dot(scr(TARGET[i]), radius=0.13, color=BLUE) for i in range(NJ)])
        cap = caption(self, "A spine is a chain of joints.")
        self.play(LaggedStart(*[FadeIn(joints[i], scale=0.5) for i in range(NJ)], lag_ratio=0.2),
                  LaggedStart(*[Create(bones[i]) for i in range(NJ - 1)], lag_ratio=0.2), run_time=2.4)
        self.wait(1)
        cap = caption(self, "An IK spine wants one smooth curve for them to follow.", cap)
        self.t0x.set_value(BEST2[0]); self.t0y.set_value(BEST2[1])
        self.t2x.set_value(BEST2[2]); self.t2y.set_value(BEST2[3])
        ghost = self.make_curve(color=DIM, width=4)
        self.play(Create(ghost), run_time=2)
        self.wait(1)
        cap = caption(self, "The curve is built from a few controls: knots.", cap)
        kn = VGroup(Dot(scr(P0), radius=0.15, color=ORANGE), Dot(scr(C), radius=0.15, color=ORANGE))
        kl = VGroup(Text("pelvis knot", font_size=24, color=ORANGE).next_to(scr(P0), LEFT, buff=0.3),
                    Text("chest knot", font_size=24, color=ORANGE).next_to(scr(C), RIGHT, buff=0.3))
        self.play(FadeIn(kn, scale=2), FadeIn(kl), run_time=1)
