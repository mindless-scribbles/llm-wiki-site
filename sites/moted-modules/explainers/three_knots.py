        panel3 = VGroup(u1, u2, u3).arrange(DOWN, aligned_edge=LEFT, buff=0.55).move_to([3.3, 0.3, 0])
        self.play(Write(u1), run_time=1.2)
        self.play(Write(u2), run_time=1.2)
        self.wait(0.5)
        cap = caption(self, "Constraints now match the unknowns. The fit is exact.", cap)
        self.play(self.blend.animate.set_value(1), run_time=4, rate_func=smooth)
        self.play(Write(u3), run_time=0.8)
        self.play(*[r.animate.set_color(GREEN) for r in rings], run_time=0.6)
        sq = Text("square: exact, not a best guess", font_size=24, color=GREEN)
        sq.next_to(panel3, DOWN, buff=0.5, aligned_edge=LEFT)
        nz = Text("miss: float noise (4.5e-12 cm)", font_size=22, color=DIM)
