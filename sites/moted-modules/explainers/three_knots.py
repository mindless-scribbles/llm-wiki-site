        self.play(FadeOut(chk), FadeOut(end_lbl), run_time=0.4)
        tl = VGroup(*[Text(f"RO_Twist 0{i+1}", font_size=24, color=BLUE).next_to(dials[i], RIGHT, buff=0.35)
                      for i in range(4)])
        self.play(LaggedStart(*[FadeIn(t, shift=LEFT * 0.2) for t in tl], lag_ratio=0.3), run_time=1.6)
