        self.play(FadeOut(VGroup(panel3, sq, nz, ml)), run_time=0.6)
        cap = caption(self, "Now twist the chain about its own axis.", cap)
        frozen = VMobject(stroke_color=DIM, stroke_width=2)
        frozen.set_points_as_corners([scr(p) for p in self.dense()[::3]])
        fitdots = VGroup(*[Dot(scr(p), radius=0.08, color=YELLOW) for p in place(self.dense())])
        self.remove(crv, fit, miss, knots_live)
        live = frozen.copy().set_color(YELLOW).set_stroke(width=5)
        kn3 = VGroup(*[Dot(scr(p), radius=0.14, color=ORANGE) for p in (P0, M_T, C)])
        self.add(live, kn3, fitdots)
        self.play(FadeOut(rings), FadeIn(joints), run_time=0.6)
        self.add(frozen)
        dials = VGroup(); marks = []
        ys = [1.9, 0.9, -0.1, -1.1]
        for y in ys:
            c = Circle(radius=0.32, color=BLUE, stroke_width=4).move_to([2.4, y, 0])
            ln = Line(c.get_center(), c.get_center() + UP * 0.32, color=BLUE, stroke_width=6)
            dials.add(VGroup(c, ln)); marks.append(ln)
        end_lbl = Text("seen end-on, per joint", font_size=22, color=DIM).next_to(dials, UP, buff=0.3).align_to(dials, LEFT)
        self.play(FadeIn(dials), FadeIn(end_lbl))
        self.play(*[Rotate(m, angle=a_, about_point=m.get_start()) for m, a_ in
                    zip(marks, [-0.7, -1.2, -0.4, -1.0])], run_time=2.4)
        self.wait(0.6)
        cap = caption(self, "The curve does not change at all.", cap)
        chk = Text("curve: identical", font_size=26, color=GREEN)
        chk.move_to([4.9, 0.6, 0])
        self.play(Indicate(live, color=GREEN, scale_factor=1.0), FadeIn(chk), run_time=1.2)
        self.wait(2)
        cap = caption(self, "A curve carries shape but no roll.", cap)
        self.wait(2)
